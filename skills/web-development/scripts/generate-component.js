#!/usr/bin/env node
/**
 * generate-component.js — scaffold a React Server Component that follows the
 * skill's coding standards (strict types, RSC by default, Tailwind, accessible).
 *
 * Usage:  node generate-component.js <ComponentName> [targetDir]
 *         targetDir defaults to ./components
 * Example: node generate-component.js PricingTable src/components
 *
 * Zero dependencies — Node built-ins only.
 */

const fs = require("fs");
const path = require("path");

const rawName = process.argv[2];
if (!rawName) {
  console.error("Usage: node generate-component.js <ComponentName> [targetDir]");
  process.exit(1);
}

// Normalize to PascalCase for the component, kebab-case for the file.
const pascal = rawName
  .replace(/[^a-zA-Z0-9]+/g, " ")
  .trim()
  .split(/\s+/)
  .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
  .join("");
const kebab = pascal.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const targetDir = path.resolve(process.argv[3] || "components");
const filePath = path.join(targetDir, `${kebab}.tsx`);

if (fs.existsSync(filePath)) {
  console.error(`Refusing to overwrite existing file: ${filePath}`);
  process.exit(1);
}

const template = `// ${pascal} — generated by the web-development skill.
// Server Component by default. Add "use client" only if it needs interactivity.

interface ${pascal}Props {
  className?: string;
}

export function ${pascal}({ className }: ${pascal}Props) {
  return (
    <section className={\`text-zinc-50 \${className ?? ""}\`}>
      <h2 className="text-2xl font-bold tracking-tight">${pascal}</h2>
      {/* TODO: implement */}
    </section>
  );
}
`;

fs.mkdirSync(targetDir, { recursive: true });
fs.writeFileSync(filePath, template);
console.log(`Created ${filePath}`);
